/* --- State --- */

static bool ring_ready = false;
static uint8_t ring_blocks = 0;          /* memory blocks the channel actually got */

/* Everything the endpoints can write is volatile: those handlers run on the
   web-server task while ring_poll() reads the same words on the loop task. All
   of them are single aligned scalars, so the worst a collision can cost is one
   frame composed from a half-applied setting — 25ms of the old brightness. */
static volatile bool ring_enabled = true;
static volatile uint8_t ring_brightness = RING_BRIGHT_DEFAULT;   /* percent, 0..100 */
static volatile uint16_t ring_night_from = RING_NIGHT_FROM_DEFAULT;
static volatile uint16_t ring_night_to = RING_NIGHT_TO_DEFAULT;

static volatile bool ring_cfg_dirty = false;
static volatile unsigned long ring_cfg_save_at = 0;

/* One-shot overlays. Only one can run at a time: they are all half a second
   long and stacking them would say nothing a single one does not. */
enum { RING_FX_NONE = 0, RING_FX_COMET, RING_FX_WIPE };
static volatile uint8_t ring_fx = RING_FX_NONE;
static volatile uint8_t ring_fx_level = NOTIFY_INFO;
static volatile unsigned long ring_fx_start = 0;

/* Knob tracking. ui_poll() hands over each detent; the position is free-running
   modulo the ring so that turning past the last pixel arrives at the first,
   exactly as the menu wraps rather than clamps. */
static int ring_knob_pos = 0;
static unsigned long ring_knob_at = 0;

/* Progress, 0..100, or -1 for "no job". Fed from loop(); nothing in ir.cpp
   knows this exists. */
static int ring_progress_pct = -1;

/* Test pattern, so colours can be judged without inventing a notification. */
enum { RING_TEST_NONE = 0, RING_TEST_BREATHE, RING_TEST_LEVELS };
static volatile uint8_t ring_test = RING_TEST_NONE;
static volatile uint8_t ring_test_level = NOTIFY_INFO;
static volatile unsigned long ring_test_until = 0;

/* GRB bytes as they go on the wire, and the last set the peripheral accepted. */
static uint8_t ring_frame[RING_LEDS][3];
static uint8_t ring_sent[RING_LEDS][3];
static bool ring_sent_valid = false;

/* 768 bytes, in .bss rather than on the loop task's stack. */
static rmt_data_t ring_sym[RING_BITS];

/* --- Colour maths --- */

/* One channel of one pixel: perceptual scale, gamma encode, then the linear
   cap. See the header comment for why that order and not another. */
static uint8_t ring_level(uint8_t channel, uint8_t envelope) {
    uint16_t perceptual = ((uint16_t)channel * envelope) / 255;
    return (uint8_t)(((uint16_t)ring_gamma[perceptual] * ring_brightness) / 100);
}

static void ring_put(uint8_t frame[RING_LEDS][3], int i, const RingColor &c,
                     uint8_t envelope) {
    if (i < 0 || i >= RING_LEDS) return;
    frame[i][0] = ring_level(c.g, envelope);   /* WS2812 takes GRB on the wire */
    frame[i][1] = ring_level(c.r, envelope);
    frame[i][2] = ring_level(c.b, envelope);
}

/* 0 -> 255 -> 0 across cycle_ms, phased on the wall clock rather than on the
   effect's start, so that a ring which changes colour mid-breath continues the
   breath instead of restarting it. */
static uint8_t ring_triangle(unsigned long now, unsigned long cycle_ms) {
    unsigned long pos = now % cycle_ms;
    unsigned long half = cycle_ms / 2;
    unsigned long up = (pos < half) ? pos : (cycle_ms - pos);
    return (uint8_t)(up * 255 / half);
}

/* --- Night window --- */

/* from == to is an empty window, which is how the silence is turned off without
   a fourth setting. from > to wraps midnight, which is the shape most people
   actually want (22:00 to 07:00). */
static bool ring_night_now() {
    if (ring_night_from == ring_night_to) return false;
    struct tm t;
    if (!clock_local_time(t)) return false;   /* time unknown -> stay lit */
    int m = t.tm_hour * 60 + t.tm_min;
    if (ring_night_from < ring_night_to)
        return m >= ring_night_from && m < ring_night_to;
    return m >= ring_night_from || m < ring_night_to;
}

/* --- Effect triggers (called from loop(), ui.h and the endpoints) --- */

static void ring_fire(uint8_t fx, uint8_t level) {
    ring_fx = fx;
    ring_fx_level = level;
    ring_fx_start = millis();
}

static void ring_knob(int steps) {
    if (steps == 0) return;
    ring_knob_pos = (ring_knob_pos + steps) % RING_LEDS;
    if (ring_knob_pos < 0) ring_knob_pos += RING_LEDS;
    ring_knob_at = millis();
}

static void ring_progress_set(int pct) {
    if (pct < 0) pct = 0;
    if (pct > 100) pct = 100;
    ring_progress_pct = pct;
}

static void ring_progress_clear() {
    ring_progress_pct = -1;
}

/* --- Frame composition ---
 *
 * Priority, highest first:
 *
 *   knob      a hand is on the control; that hand's feedback outranks anything
 *             the ring was saying on its own
 *   test      an operator asked for this pattern explicitly
 *   one-shot  arrival or acknowledgement, half a second each
 *   progress  a job is running and its position is the information
 *   breathe   unread messages exist
 *   dark      nothing to say
 *
 * `now` is passed in rather than read here: ring_poll() retires expired effects
 * against one timestamp, and composing against a second one taken microseconds
 * later would let an effect be drawn one millisecond past its own end — which
 * for the wipe's fade is the difference between reaching zero and wrapping past
 * it to full brightness.
 */
static void ring_compose(uint8_t frame[RING_LEDS][3], unsigned long now) {
    memset(frame, 0, RING_LEDS * 3);

    /* Disabled, or inside the night window: composed dark and pushed once, so
       the ring goes out rather than freezing on its last frame. */
    if (!ring_enabled || ring_night_now()) return;

    if (now - ring_knob_at < RING_KNOB_HOLD_MS) {
        ring_put(frame, ring_knob_pos, RING_C_WARN, 255);
        return;
    }

    if (ring_test != RING_TEST_NONE) {
        if (ring_test == RING_TEST_LEVELS) {
            /* Two pixels each with a gap between, so the three can be compared
               side by side at whatever brightness is currently set. */
            ring_put(frame, 0, RING_C_INFO, 255);
            ring_put(frame, 1, RING_C_INFO, 255);
            ring_put(frame, 3, RING_C_WARN, 255);
            ring_put(frame, 4, RING_C_WARN, 255);
            ring_put(frame, 6, RING_C_CRIT, 255);
            ring_put(frame, 7, RING_C_CRIT, 255);
        } else {
            uint8_t env = RING_BREATHE_MIN +
                          (uint8_t)((255 - RING_BREATHE_MIN) *
                                    ring_triangle(now, RING_BREATHE_MS) / 255);
            for (int i = 0; i < RING_LEDS; i++)
                ring_put(frame, i, ring_level_color(ring_test_level), env);
        }
        return;
    }

    if (ring_fx == RING_FX_COMET) {
        unsigned long el = now - ring_fx_start;
        int head = (int)(el * RING_LEDS / RING_COMET_MS);
        const RingColor &c = ring_level_color(ring_fx_level);
        /* Head at full, then a tail that falls away behind it. The tail is what
           makes the lap read as a direction rather than a chase of blinks. */
        static const uint8_t tail[RING_COMET_TAIL + 1] = {255, 110, 45, 15};
        for (int t = 0; t <= RING_COMET_TAIL; t++) {
            int p = head - t;
            if (p < 0) p += RING_LEDS;
            ring_put(frame, p % RING_LEDS, c, tail[t]);
        }
        return;
    }

    if (ring_fx == RING_FX_WIPE) {
        unsigned long el = now - ring_fx_start;
        unsigned long fill_ms = RING_WIPE_MS - RING_WIPE_FADE_MS;
        int lit = (int)(el * RING_LEDS / fill_ms);
        if (lit > RING_LEDS) lit = RING_LEDS;
        uint8_t env = 255;
        if (el > fill_ms) {
            unsigned long f = el - fill_ms;
            if (f > RING_WIPE_FADE_MS) f = RING_WIPE_FADE_MS;
            env = (uint8_t)(255 - (f * 255 / RING_WIPE_FADE_MS));
        }
        for (int i = 0; i < lit; i++) ring_put(frame, i, RING_C_ACK, env);
        return;
    }

    if (ring_progress_pct >= 0) {
        /* The lit arc is the progress. The pixel at the boundary carries the
           fraction, so eight LEDs read as rather more than eight steps, and it
           never goes fully dark while a job is running — a blast that has not
           yet sent its first frame is still a blast, and an unlit ring would
           say the opposite. */
        int scaled = ring_progress_pct * RING_LEDS;         /* 0..800 */
        int whole = scaled / 100;
        int part = scaled % 100;
        for (int i = 0; i < whole && i < RING_LEDS; i++)
            ring_put(frame, i, RING_C_WARN, 255);
        if (whole < RING_LEDS) {
            int env = part * 255 / 100;
            if (env < 40) env = 40;
            ring_put(frame, whole, RING_C_WARN, (uint8_t)env);
        }
        return;
    }

    uint8_t top;
    if (notify_top_unread_level(top)) {
        unsigned long cycle = (top == NOTIFY_CRIT) ? RING_BREATHE_CRIT_MS
                                                   : RING_BREATHE_MS;
        uint8_t env = RING_BREATHE_MIN +
                      (uint8_t)((255 - RING_BREATHE_MIN) *
                                ring_triangle(now, cycle) / 255);
        for (int i = 0; i < RING_LEDS; i++)
            ring_put(frame, i, ring_level_color(top), env);
    }
}

/* --- Transmission --- */

static void ring_encode() {
    const uint8_t *bytes = &ring_frame[0][0];
    int s = 0;
    for (int b = 0; b < RING_LEDS * 3; b++) {
        uint8_t v = bytes[b];
        for (int bit = 7; bit >= 0; bit--) {
            bool one = (v >> bit) & 1;
            ring_sym[s].level0 = 1;
            ring_sym[s].duration0 = one ? RING_T1H : RING_T0H;
            ring_sym[s].level1 = 0;
            ring_sym[s].duration1 = one ? RING_T1L : RING_T0L;
            s++;
        }
    }
}

/* --- Persistence --- */

static void ring_cfg_save() {
    JsonDocument doc;
    doc["on"] = ring_enabled;
    doc["b"] = ring_brightness;
    doc["nf"] = ring_night_from;
    doc["nt"] = ring_night_to;
    String out;
    serializeJson(doc, out);
    write_spiffs_file_atomic(RING_CFG_FILE, RING_CFG_TMP, out);
}

static void ring_cfg_mark_dirty() {
    unsigned long at = millis() + RING_CFG_DELAY_MS;
    if (!ring_cfg_dirty || (long)(at - ring_cfg_save_at) < 0) ring_cfg_save_at = at;
    ring_cfg_dirty = true;
}

/* A file that is missing, truncated or nonsense leaves the compiled defaults
   standing: the ring is a notification channel, and the worst outcome of a bad
   config read is that it silently stops being one. */
static void ring_cfg_load() {
    String raw = read_spiffs_file(RING_CFG_FILE);
    if (raw.length() == 0) return;
    JsonDocument doc;
    if (deserializeJson(doc, raw) != DeserializationError::Ok) return;
    if (doc["on"].is<bool>()) ring_enabled = doc["on"].as<bool>();
    if (doc["b"].is<int>()) {
        int b = doc["b"].as<int>();
        if (b >= 0 && b <= 100) ring_brightness = (uint8_t)b;
    }
    if (doc["nf"].is<int>() && doc["nt"].is<int>()) {
        int f = doc["nf"].as<int>(), t = doc["nt"].as<int>();
        if (f >= 0 && f < 1440 && t >= 0 && t < 1440) {
            ring_night_from = (uint16_t)f;
            ring_night_to = (uint16_t)t;
        }
    }
}

/* --- Poll --- */

static const char *ring_effect_name() {
    if (!ring_ready) return "unavailable";
    if (!ring_enabled) return "disabled";
    if (ring_night_now()) return "night";
    if (millis() - ring_knob_at < RING_KNOB_HOLD_MS) return "knob";
    if (ring_test == RING_TEST_LEVELS) return "test-levels";
    if (ring_test == RING_TEST_BREATHE) return "test-breathe";
    if (ring_fx == RING_FX_COMET) return "comet";
    if (ring_fx == RING_FX_WIPE) return "wipe";
    if (ring_progress_pct >= 0) return "progress";
    uint8_t top;
    if (notify_top_unread_level(top)) return "breathe";
    return "idle";
}

/* Called every loop() pass; does real work RING_FRAME_MS apart at most. */
static void ring_poll() {
    if (!ring_ready) return;

    unsigned long now = millis();
    static unsigned long last_frame = 0;
    if (now - last_frame < RING_FRAME_MS) return;
    last_frame = now;

    if (ring_cfg_dirty && (long)(now - ring_cfg_save_at) >= 0) {
        ring_cfg_dirty = false;
        ring_cfg_save();
    }

    /* Arrivals and acknowledgements are consumed whatever the ring is doing —
       including while it is disabled or silenced — so that a night's worth of
       them cannot queue up and all fire at eight in the morning. Both flags are
       taken every pass and the arrival wins the frame; leaving the other one
       standing would show it a moment later, on top of whatever came next. */
    uint8_t level;
    bool acked = notify_take_ring_ack();
    if (notify_take_ring_arrival(&level)) ring_fire(RING_FX_COMET, level);
    else if (acked) ring_fire(RING_FX_WIPE, NOTIFY_INFO);

    if (ring_fx == RING_FX_COMET && now - ring_fx_start >= RING_COMET_MS)
        ring_fx = RING_FX_NONE;
    if (ring_fx == RING_FX_WIPE && now - ring_fx_start >= RING_WIPE_MS)
        ring_fx = RING_FX_NONE;
    if (ring_test != RING_TEST_NONE && (long)(now - ring_test_until) >= 0)
        ring_test = RING_TEST_NONE;

    uint8_t want[RING_LEDS][3];
    ring_compose(want, now);

    if (ring_sent_valid && memcmp(want, ring_sent, sizeof(want)) == 0) return;

    /* The peripheral reads ring_sym asynchronously after rmtWriteAsync(), so
       the buffer must not be rewritten until it says it is finished. At 230us
       of transmission against a 25ms frame this never fires in practice; it is
       here because "never in practice" is not the same as "never". */
    if (!rmtTransmitCompleted(PIN_WS2812)) return;

    memcpy(ring_frame, want, sizeof(ring_frame));
    ring_encode();
    if (rmtWriteAsync(PIN_WS2812, ring_sym, RING_BITS)) {
        memcpy(ring_sent, want, sizeof(ring_sent));
        ring_sent_valid = true;
    }
}

