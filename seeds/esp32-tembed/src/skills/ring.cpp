/*
 * ring.cpp — the 8-LED WS2812 ring around the encoder, as the pager's second
 * output channel.
 *
 * The screen says what happened. The ring says that something happened, from
 * across a room, without being read. That is the whole division of labour, and
 * it is why almost everything here is a *state* rather than a flash: while an
 * unread message exists the ring breathes in that message's colour, and it
 * keeps breathing until somebody acknowledges it.
 *
 *
 * RMT coexistence with the IR transmitter — the thing that had to be settled
 * ------------------------------------------------------------------------
 * ir.cpp already owns an RMT TX channel (rmtInit(PIN_IR_TX, RMT_TX_MODE,
 * RMT_MEM_NUM_BLOCKS_2, 1000000)), and WS2812 also wants one. The numbers, from
 * the SoC caps header the build actually compiles against
 * (framework-arduinoespressif32-libs/esp32s3/include/soc/esp32s3/include/soc/
 * soc_caps.h):
 *
 *   SOC_RMT_GROUPS                  1
 *   SOC_RMT_CHANNELS_PER_GROUP      8
 *   SOC_RMT_TX_CANDIDATES_PER_GROUP 4     <- only four of the eight can transmit
 *   SOC_RMT_MEM_WORDS_PER_CHANNEL   48    <- one "memory block" is 48 symbols
 *
 * A channel asking for N memory blocks takes its own block plus the blocks of
 * the N-1 TX channels after it, so IR's two blocks cost two of the four TX
 * candidates and leave two. That is what this file spends, and it means the
 * ESP32-S3's TX side is now fully committed: a third RMT TX consumer added
 * later will fail at rmtInit() rather than quietly steal a channel.
 *
 * The Arduino core's wrapper (cores/esp32/esp32-hal-rmt.c in arduino-esp32
 * 3.3.9) keys everything on the *pin*: rmtInit() allocates one rmt_obj_s per
 * pin, each with its own IDF channel handle from rmt_new_tx_channel(), its own
 * copy encoder, its own event group and its own mutex — RMT_MUTEX_LOCK() takes
 * busptr->g_rmt_objlocks, not a global. The only shared lock, g_rmt_block_lock,
 * is held across allocation and released before any transmission. So two pins
 * transmit concurrently with no interlock between them, and a ring refresh
 * cannot stall or corrupt a frame the IR channel is clocking out.
 *
 * FastLED was never a candidate, for the reason recorded in the reference
 * firmware for this same board (tembed-pager/firmware/platformio.ini): it
 * claims every RMT TX channel on the first show() and installs a non-shared RMT
 * interrupt handler, which on a board that also transmits IR is a collision by
 * construction.
 *
 * Adafruit NeoPixel was that reference's choice and it is the right one there —
 * but that firmware builds on espressif32@6.13.0 (arduino-esp32 2.x, IDF 4) and
 * this one builds on arduino-esp32 3.3.9 (IDF 5), and on IDF 5 NeoPixel 1.12.3
 * is no longer a driver at all. Its whole ESP32 path (esp.c, the HAS_ESP_IDF_5
 * branch) is:
 *
 *     rmtInit(pin, RMT_TX_MODE, RMT_MEM_NUM_BLOCKS_1, 10000000);
 *     ... pack numBytes*8 rmt_data_t on the stack ...
 *     rmtWrite(pin, led_data, numBytes * 8, RMT_WAIT_FOR_EVER);
 *
 * — the very core wrapper this file would call anyway. Adding the library would
 * buy nothing and cost three things: a blocking rmtWrite() that parks the loop
 * task for the length of the bit stream, a variable-length rmt_data_t array on
 * that task's stack (768 bytes here) rather than in .bss, and a second copy of
 * the pixel buffer. So the ring is driven through the same rmt* wrapper ir.cpp
 * uses, with rmtWriteAsync() instead — identical peripheral arrangement to the
 * proven reference, minus the blocking.
 *
 * Timings below are NeoPixel's, unchanged, because they are what is known to
 * work on this board's ring: a 10MHz channel, so one tick is 100ns.
 *
 *
 * Not blocking, and not glitching
 * -------------------------------
 * The 800kHz bit stream is generated by the peripheral, not the CPU: 192 bits
 * at 1.2us is about 230us of hardware transmission per frame, started by a
 * non-blocking rmtWriteAsync() and never waited on. loop() spends only the
 * encode — 192 iterations of two bitfield stores — and ring_poll() runs at most
 * once every RING_FRAME_MS, so the ring costs a bounded fraction of a
 * millisecond twenty-five times a second and cannot delay ir_poll().
 *
 * Two guards keep the stream itself intact:
 *
 *   - the symbol buffer is not touched while the peripheral owns it. A frame is
 *     encoded only after rmtTransmitCompleted() says the previous one is done;
 *     otherwise the frame is dropped and retried on the next pass.
 *   - a frame is only sent when the composed pixels differ from the last ones
 *     actually accepted, so a still ring — the common case — puts nothing on
 *     the wire at all.
 *
 * With one memory block the copy encoder's refill interrupt would fire every 24
 * symbols (30us); two blocks halve that to every 48 (60us), which is the margin
 * that WiFi and AsyncTCP interrupt latency is being padded against — the same
 * reasoning, and the same choice, as ir.cpp's two blocks. If two blocks cannot
 * be had the init falls back to one rather than leaving the ring dark, and says
 * which it got.
 *
 * A glitched WS2812 frame is a wrong colour for 40ms and self-corrects on the
 * next one. That asymmetry is the point of the arrangement above: the failure
 * that must not happen is a glitched IR blast, and IR is on its own channel,
 * with its own memory, its own mutex and its own interrupt, untouched by any of
 * this.
 *
 *
 * Brightness, gamma and night
 * ---------------------------
 * ring_level() is where a colour becomes a drive value, and the order of the
 * three operations is deliberate:
 *
 *   1. the channel is scaled by the effect's envelope, in perceptual space —
 *      this is what a breath or a comet tail means;
 *   2. the result is gamma-encoded through ring_gamma[], because a WS2812's
 *      output is roughly linear in its PWM value while the eye is not. Without
 *      it a breath is a snap to full followed by a plateau, and at the bottom
 *      of the ramp every colour collapses towards grey;
 *   3. only then is the global cap applied, linearly. That keeps "50%" meaning
 *      half the drive current — a power cap with a predictable effect — rather
 *      than a second gamma curve multiplied into the first.
 *
 * The cap is runtime-settable over HTTP because its value is provisional by
 * design; 50 is a starting point to be dialled in against the actual room, not
 * a measurement.
 *
 * Night silence is absolute: inside the window the ring does not light, not
 * even for an unread critical, which already breathes on the (dim) screen.
 * Boundaries come from clock_local_time() and therefore from whatever POSIX TZ
 * string SPIFFS holds — this file knows no city and no offset, and must not
 * learn one. When the clock has never been set the ring stays lit: a node that
 * has not reached NTP is usually a freshly booted or offline one, and a pager
 * that goes dark because it lost the time is broken in the direction that loses
 * messages.
 */

/* --- Geometry and rates --- */

#define RING_LEDS         8
#define RING_BITS         (RING_LEDS * 3 * 8)

/* 40Hz. Fast enough that a breath has no visible steps and a comet head moves
   smoothly, slow enough that the RMT channel is busy under 1% of the time. */
#define RING_FRAME_MS     25

/* WS2812 bit cells at 100ns per tick, from Adafruit NeoPixel's IDF 5 path. */
#define RING_T0H          4
#define RING_T0L          8
#define RING_T1H          8
#define RING_T1L          4

/* The reset that latches a frame is the line sitting low between writes, which
   rmtSetEOT(LOW) guarantees; at RING_FRAME_MS apart that gap is four orders of
   magnitude longer than the ~50us the part needs, so no reset symbol is sent. */

/* --- Effect durations --- */

#define RING_COMET_MS     640    /* one lap, 80ms a pixel */
#define RING_COMET_TAIL   3
#define RING_WIPE_MS      560    /* fill, then fade */
#define RING_WIPE_FADE_MS 160
#define RING_KNOB_HOLD_MS 400    /* the dot lingers this long after the last detent */
#define RING_BREATHE_MS   4000   /* info and warn */
#define RING_BREATHE_CRIT_MS 2000 /* matches the clock face's rule breathe */

/* The breath's floor, in envelope units before gamma. Zero would make the ring
   vanish at the bottom of every cycle, and "you have messages" must not blink
   out of existence — this is a faint ember rather than darkness. */
#define RING_BREATHE_MIN  80

/* --- Configuration --- */

#define RING_CFG_FILE     "/ring.json"
#define RING_CFG_TMP      "/ring.tmp"
/* Settings arrive on the web-server task; the flash write is deferred to
   loop(), the one task allowed to spend milliseconds. Same arrangement, and the
   same reason, as the notification store's snapshot. */
#define RING_CFG_DELAY_MS 1500

#define RING_BRIGHT_DEFAULT     50
#define RING_NIGHT_FROM_DEFAULT 0        /* 00:00 */
#define RING_NIGHT_TO_DEFAULT   (8 * 60) /* 08:00 */

#define RING_TEST_MAX_S   60
#define RING_TEST_DEF_S   8

/* --- Palette ---
 *
 * The three level colours are the RGB888 equivalents of the RGB565 the clock
 * face already uses (COL_INFO, COL_ACCENT, COL_CRIT), so that a message which
 * is amber on the screen is the same amber on the ring rather than a second
 * opinion about what "warn" looks like. Green belongs to acknowledgement only
 * and appears nowhere else in the UI. */

struct RingColor { uint8_t r, g, b; };

static const RingColor RING_C_INFO = { 41, 239, 173};  /* teal   <- COL_INFO   */
static const RingColor RING_C_WARN = {255, 162,  41};  /* amber  <- COL_ACCENT */
static const RingColor RING_C_CRIT = {230,  57,  41};  /* red    <- COL_CRIT   */
static const RingColor RING_C_ACK  = { 60, 220,  80};  /* green, acknowledge   */
static const RingColor RING_C_OFF  = {  0,   0,   0};

static const RingColor &ring_level_color(uint8_t level) {
    switch (level) {
        case NOTIFY_CRIT: return RING_C_CRIT;
        case NOTIFY_WARN: return RING_C_WARN;
        default:          return RING_C_INFO;
    }
}

