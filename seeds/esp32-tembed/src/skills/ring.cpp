static void ring_time_str(uint16_t mins, char *out, size_t n) {
    snprintf(out, n, "%02u:%02u", (unsigned)(mins / 60), (unsigned)(mins % 60));
}

/* Accepts "HH:MM" or a plain minute count, because one of those is what a
   person types and the other is what a script already has.
 *
 * Parsed by hand rather than with sscanf(): nothing else in this firmware calls
 * the scanf family, and linking it in for five characters costs roughly 25KB of
 * flash. Five characters exactly — "8:30" is rejected rather than guessed at,
 * which also makes the format that comes back out the only one accepted. */
static bool ring_parse_time(JsonVariantConst v, uint16_t &out) {
    if (v.is<const char *>()) {
        const char *s = v.as<const char *>();
        if (!s || strlen(s) != 5 || s[2] != ':') return false;
        for (int i = 0; i < 5; i++) {
            if (i == 2) continue;
            if (s[i] < '0' || s[i] > '9') return false;
        }
        int h = (s[0] - '0') * 10 + (s[1] - '0');
        int m = (s[3] - '0') * 10 + (s[4] - '0');
        if (h > 23 || m > 59) return false;
        out = (uint16_t)(h * 60 + m);
        return true;
    }
    if (v.is<int>()) {
        int m = v.as<int>();
        if (m < 0 || m > 1439) return false;
        out = (uint16_t)m;
        return true;
    }
    return false;
}

static void ring_state_json(JsonDocument &doc) {
    char from[8], to[8];
    ring_time_str(ring_night_from, from, sizeof(from));
    ring_time_str(ring_night_to, to, sizeof(to));

    doc["ready"] = ring_ready;
    doc["leds"] = RING_LEDS;
    doc["pin"] = PIN_WS2812;
    doc["mem_blocks"] = ring_blocks;
    doc["enabled"] = ring_enabled;
    doc["brightness"] = ring_brightness;
    doc["night_from"] = from;
    doc["night_to"] = to;
    doc["night_now"] = ring_night_now();
    doc["effect"] = ring_effect_name();
    doc["unread"] = notify_unread_count();
    uint8_t top;
    if (notify_top_unread_level(top)) doc["level"] = notify_level_name(top);
    if (ring_progress_pct >= 0) doc["progress"] = ring_progress_pct;
}

/* notify_take_body() and notify_send_error() are notify.cpp's, reused rather
   than copied: the skills are #included into one translation unit, and a third
   identical pair of four-line JSON helpers would be three too many. Every route
   below is registered with AsyncURIMatcher::exact(), without which /ring would
   also answer /ring/test and every test request would be read as a settings
   change with no body. */
static void ring_register_routes(AsyncWebServer &server) {

    server.on(AsyncURIMatcher::exact("/ring"), HTTP_GET, [](AsyncWebServerRequest *req) {
        if (!require_auth(req)) return;
        JsonDocument doc;
        ring_state_json(doc);
        String out;
        serializeJson(doc, out);
        req->send(200, "application/json", out);
    });

    /* Bodies are collected by handle_body_collect() into _tempObject and belong
       to the handler from then on, including on the unauthenticated path —
       hence check_auth() rather than require_auth()'s early return. */
    server.on(AsyncURIMatcher::exact("/ring"), HTTP_POST, [](AsyncWebServerRequest *req) {
        char *body = notify_take_body(req);
        if (!check_auth(req)) {
            free(body);
            notify_send_error(req, 401, "Authorization: Bearer <token> required");
            return;
        }
        if (!body) {
            notify_send_error(req, 400, "body must be JSON");
            return;
        }
        JsonDocument input;
        DeserializationError err = deserializeJson(input, body);
        free(body);
        if (err != DeserializationError::Ok) {
            notify_send_error(req, 400, "invalid JSON");
            return;
        }

        /* Parsed into locals first: a body that names four settings and gets
           one of them wrong applies none of them, rather than half. */
        bool enabled = ring_enabled;
        uint8_t brightness = ring_brightness;
        uint16_t from = ring_night_from, to = ring_night_to;

        if (input["enabled"].is<bool>()) enabled = input["enabled"].as<bool>();
        else if (!input["enabled"].isNull()) {
            notify_send_error(req, 400, "enabled must be true or false");
            return;
        }
        if (input["brightness"].is<int>()) {
            int b = input["brightness"].as<int>();
            if (b < 0 || b > 100) {
                notify_send_error(req, 400, "brightness must be 0..100 (percent)");
                return;
            }
            brightness = (uint8_t)b;
        } else if (!input["brightness"].isNull()) {
            notify_send_error(req, 400, "brightness must be a number, 0..100");
            return;
        }
        if (!input["night_from"].isNull() &&
            !ring_parse_time(input["night_from"], from)) {
            notify_send_error(req, 400, "night_from must be \"HH:MM\" or minutes past midnight");
            return;
        }
        if (!input["night_to"].isNull() &&
            !ring_parse_time(input["night_to"], to)) {
            notify_send_error(req, 400, "night_to must be \"HH:MM\" or minutes past midnight");
            return;
        }

        bool changed = (enabled != ring_enabled) || (brightness != ring_brightness) ||
                       (from != ring_night_from) || (to != ring_night_to);
        ring_enabled = enabled;
        ring_brightness = brightness;
        ring_night_from = from;
        ring_night_to = to;
        if (changed) {
            ring_cfg_mark_dirty();
            event_add("ring: %s, brightness %u%%, quiet %02u:%02u-%02u:%02u",
                      ring_enabled ? "on" : "off", (unsigned)ring_brightness,
                      (unsigned)(ring_night_from / 60), (unsigned)(ring_night_from % 60),
                      (unsigned)(ring_night_to / 60), (unsigned)(ring_night_to % 60));
        }

        JsonDocument doc;
        doc["ok"] = true;
        ring_state_json(doc);
        String out;
        serializeJson(doc, out);
        req->send(200, "application/json", out);
    }, NULL, handle_body_collect);

    server.on(AsyncURIMatcher::exact("/ring/test"), HTTP_POST, [](AsyncWebServerRequest *req) {
        char *body = notify_take_body(req);
        if (!check_auth(req)) {
            free(body);
            notify_send_error(req, 401, "Authorization: Bearer <token> required");
            return;
        }
        if (!body) {
            notify_send_error(req, 400, "body must be JSON with an effect");
            return;
        }
        JsonDocument input;
        DeserializationError err = deserializeJson(input, body);
        free(body);
        if (err != DeserializationError::Ok) {
            notify_send_error(req, 400, "invalid JSON");
            return;
        }

        const char *effect = input["effect"] | "levels";
        uint8_t level = NOTIFY_INFO;
        if (input["level"].is<const char *>() &&
            !notify_level_parse(input["level"].as<const char *>(), level)) {
            notify_send_error(req, 400, "level must be info, warn or crit");
            return;
        }
        int seconds = input["seconds"] | RING_TEST_DEF_S;
        if (seconds < 1 || seconds > RING_TEST_MAX_S) {
            notify_send_error(req, 400, "seconds must be 1..60");
            return;
        }

        if (strcmp(effect, "off") == 0) {
            ring_test = RING_TEST_NONE;
            ring_fx = RING_FX_NONE;
        } else if (strcmp(effect, "levels") == 0) {
            ring_test = RING_TEST_LEVELS;
            ring_test_until = millis() + (unsigned long)seconds * 1000UL;
        } else if (strcmp(effect, "breathe") == 0) {
            ring_test = RING_TEST_BREATHE;
            ring_test_level = level;
            ring_test_until = millis() + (unsigned long)seconds * 1000UL;
        } else if (strcmp(effect, "comet") == 0) {
            ring_test = RING_TEST_NONE;
            ring_fire(RING_FX_COMET, level);
        } else if (strcmp(effect, "wipe") == 0) {
            ring_test = RING_TEST_NONE;
            ring_fire(RING_FX_WIPE, NOTIFY_INFO);
        } else {
            notify_send_error(req, 400,
                              "effect must be levels, breathe, comet, wipe or off");
            return;
        }

        JsonDocument doc;
        doc["ok"] = true;
        doc["effect"] = effect;
        /* Said out loud rather than left as a mystery: the night window
           silences a test too, and the way out is the same API. */
        bool suppressed = !ring_ready || !ring_enabled || ring_night_now();
        doc["suppressed"] = suppressed;
        if (suppressed) {
            doc["reason"] = !ring_ready ? "ring unavailable"
                          : !ring_enabled ? "ring disabled"
                          : "inside the night window";
        }
        ring_state_json(doc);
        String out;
        serializeJson(doc, out);
        req->send(200, "application/json", out);
    }, NULL, handle_body_collect);
}

static const Skill ring_skill = {
    .name = "ring",
    .version = "0.1.0",
    .describe = ring_describe,
    .endpoints = ring_endpoints,
    .register_routes = ring_register_routes
};

/* Runs after skill_ir_init(), and the order is load-bearing: IR asks for two of
   the four TX memory blocks and must get them, so it allocates first and the
   ring takes what is left. Both channels are held for the life of the boot. */
static void skill_ring_init() {
    ring_cfg_load();

    /* Backdated so the very first frames are not read as "the knob was just
       turned". Unsigned wraparound makes this correct even when init runs
       before millis() has reached RING_KNOB_HOLD_MS. */
    ring_knob_at = millis() - RING_KNOB_HOLD_MS;

    /* 10MHz, so one duration tick is 100ns and the WS2812 bit cells above are
       whole numbers. Two memory blocks for interrupt-latency headroom, falling
       back to one rather than leaving the ring dark. */
    ring_blocks = 2;
    ring_ready = rmtInit(PIN_WS2812, RMT_TX_MODE, RMT_MEM_NUM_BLOCKS_2, 10000000);
    if (!ring_ready) {
        ring_blocks = 1;
        ring_ready = rmtInit(PIN_WS2812, RMT_TX_MODE, RMT_MEM_NUM_BLOCKS_1, 10000000);
    }
    if (!ring_ready) {
        ring_blocks = 0;
        event_add("ring: RMT init failed on pin %d", PIN_WS2812);
    } else {
        /* Idle low between frames: that gap is the WS2812 latch, and a line
           left high would be a permanent "reset never happened". */
        rmtSetEOT(PIN_WS2812, LOW);
        if (ring_blocks == 1)
            event_add("ring: only one RMT memory block available");
        /* The ring's state at reset is undefined, so the first frame is pushed
           unconditionally — ring_sent_valid is false and ring_poll() composes
           darkness on its first pass. */
    }

    skill_register(&ring_skill);
}
